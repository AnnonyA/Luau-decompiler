function queryOperator([name, body], index) {
 return `
operators.${name} = function(node, input, context)
    local output = {}
    local rejected = 0
    local state = { running = 0, high = -1000000, seen = {}, groups = {}, window = {}, segment = 0 }
    local nextCounter, readCounter = makeCounter(node.tag, ${index % 4 + 1})
    local function audit(row, ordinal)
        local current, touched = nextCounter(row.weight + ordinal % 3)
        state.high = math.max(state.high, row.value)
        return (current + touched + row.id) % 101
    end
    for index, row in rowsIterator(input, node.reverse) do
        local auditValue = audit(row, index)
        if auditValue % 5 == 0 then
            context.cacheHits += 1
        elseif auditValue % 3 == 0 then
            context.cacheMisses += 1
        else
            context.cacheMisses += 2
        end
        ${body}
        if #output > context.limit then
            fail("ROWLIMIT", node.tag)
        end
    end
    local current, touched = readCounter()
    context.operatorCounts["${name}"] = (context.operatorCounts["${name}"] or 0) + #input
    local digest = note(context, "${name}", output, rejected)
    context.audit = (context.audit + current + touched + digest + math.max(0, state.high)) % 1000003
    if #output == 0 then
        context.empty += 1
    elseif #output < #input then
        context.reduced += 1
    else
        context.expanded += #output - #input
    end
    return output, rejected, digest
end
`;
}

const queryEpilogue = `
local function scan(name)
    return { kind = "scan", name = name, tag = 0 }
end
local function walkPlan(node, visitor, depth)
    visitor(node, depth)
    if node.input then
        walkPlan(node.input, visitor, depth + 1)
    end
    if node.left then
        walkPlan(node.left, visitor, depth + 1)
    end
    if node.right then
        walkPlan(node.right, visitor, depth + 1)
    end
end
local function estimate(node, catalog)
    if node.kind == "scan" then
        return #catalog[node.name], 1
    elseif node.kind == "join" then
        local leftRows, leftCost = estimate(node.left, catalog)
        local rightRows, rightCost = estimate(node.right, catalog)
        return math.floor(leftRows * rightRows / 5), leftCost + rightCost + leftRows * rightRows
    elseif node.kind == "union" then
        local leftRows, leftCost = estimate(node.left, catalog)
        local rightRows, rightCost = estimate(node.right, catalog)
        return leftRows + rightRows, leftCost + rightCost + 1
    end
    local rows, cost = estimate(node.input, catalog)
    if node.kind == "select" or node.kind == "threshold" then
        return math.floor(rows / 2), cost + rows
    elseif node.kind == "expand" then
        return rows * 2, cost + rows * 2
    elseif node.kind == "sort" then
        return rows, cost + rows * 3
    else
        return rows, cost + rows
    end
end
local function optimize(node, changes)
    local copy = table.clone(node)
    if node.input then
        copy.input = optimize(node.input, changes)
    end
    if node.left then
        copy.left = optimize(node.left, changes)
    end
    if node.right then
        copy.right = optimize(node.right, changes)
    end
    if node.expression then
        copy.expression = foldExpression(node.expression)
        changes.expressions += 1
    end
    if node.predicate then
        copy.predicate = foldExpression(node.predicate)
        changes.predicates += 1
    end
    if copy.kind == "select" and copy.input.kind == "select" then
        copy.predicate = binary("and", copy.input.predicate, copy.predicate)
        copy.input = copy.input.input
        changes.merged += 1
    end
    return copy
end
local function execute(node, context)
    context.calls += 1
    if context.calls > 300 then
        fail("PLANDEPTH", context.calls)
    end
    if node.kind == "scan" then
        local source = context.catalog[node.name]
        if not source then
            fail("TABLE", node.name)
        end
        local rows = {}
        for index = 1, #source do
            append(rows, source[index], 0)
        end
        note(context, "scan:" .. node.name, rows, 0)
        return rows
    elseif node.kind == "union" then
        local left = execute(node.left, context)
        local right = execute(node.right, context)
        for index = 1, #right do
            append(left, right[index], node.tag)
        end
        note(context, "union", left, #right)
        return left
    elseif node.kind == "join" then
        local left = execute(node.left, context)
        local right = execute(node.right, context)
        local buckets = {}
        for index, row in rowsIterator(right, false) do
            local bucket = buckets[row.group]
            if not bucket then
                bucket = {}
                buckets[row.group] = bucket
            end
            bucket[#bucket + 1] = row
        end
        local output = {}
        for index, row in rowsIterator(left, false) do
            local bucket = buckets[row.group]
            if bucket then
                for rightIndex = 1, #bucket do
                    local merged = row + bucket[rightIndex]
                    merged.rank = index * 10 + rightIndex
                    append(output, merged, node.tag)
                end
            elseif node.outer then
                local copy = append(output, row, -node.tag)
                copy.flag = false
            end
        end
        note(context, "join", output, #right)
        return output
    end
    local input = execute(node.input, context)
    if node.kind == "sort" then
        table.sort(input, function(left, right)
            local leftScore = left.value * node.factor + left.weight
            local rightScore = right.value * node.factor + right.weight
            if leftScore == rightScore then
                if left.id == right.id then
                    return left.rank < right.rank
                end
                return left.id < right.id
            end
            return node.reverse and leftScore > rightScore or not node.reverse and leftScore < rightScore
        end)
        note(context, "sort", input, node.factor)
        return input
    elseif node.kind == "group" then
        local groups = {}
        for index, row in rowsIterator(input, false) do
            local key = row.group
            if groups[key] then
                groups[key] = groups[key] + row
                groups[key].rank += 1
            else
                groups[key] = rowWithMeta(copyRow(row))
                groups[key].rank = 1
            end
        end
        local output = {}
        for key = 0, 4 do
            if groups[key] then
                append(output, groups[key], node.tag)
            end
        end
        note(context, "group", output, #input)
        return output
    end
    local operator = operators[node.kind]
    if not operator then
        fail("OPERATOR", node.kind)
    end
    return operator(node, input, context)
end
local names = { ${queryOperators.map(([n]) => `"${n}"`).join(', ')} }
local catalog = buildCatalog()
local totals = { digest = 0, rows = 0, visits = 0, audit = 0 }
local function contextFor(index)
    return {
        catalog = catalog, parameters = { floor = seed % 11 - 5, boost = mode + 2 },
        effects = {}, operatorCounts = {}, visits = 0, cacheHits = 0, cacheMisses = 0,
        calls = 0, limit = 500, audit = index, empty = 0, reduced = 0, expanded = 0,
    }
end
local function stage(name, input, index)
    return {
        kind = name, input = input, tag = index * 11, factor = index % 5 + 2,
        offset = (index + mode) % 4 + 1, reverse = (index + mode) % 2 == 0,
        predicate = binary("greater", field("value"), { kind = "parameter", name = "floor" }),
        expression = {
            kind = "choose", test = field("flag"),
            yes = binary("add", field("value"), binary("multiply", literal(2), literal(3))),
            no = binary("subtract", field("balance"), { kind = "parameter", name = "boost" }),
        },
    }
end
emit("query-planner", seed, mode)
for index = 1, #names do
    local base
    if index % 3 == 0 then
        base = { kind = "join", left = scan("sales"), right = scan("rates"), tag = index, outer = mode % 2 == 0 }
    elseif index % 3 == 1 then
        base = { kind = "union", left = scan("sales"), right = scan("returns"), tag = index }
    else
        base = scan("sales")
    end
    local filtered = stage("select", stage("select", base, index + 1), index + 2)
    if index % 4 == 0 then
        filtered.predicate = binary("or", field("flag"), filtered.predicate)
    end
    local selected = stage(names[index], filtered, index)
    local projected = stage("project", selected, index + 3)
    local plan = { kind = "sort", input = projected, factor = index % 3 + 1, reverse = mode % 2 == 1 }
    if index % 2 == 0 then
        plan = { kind = "group", input = plan, tag = index + 100 }
    end
    local changes = { expressions = 0, predicates = 0, merged = 0 }
    local optimized = optimize(plan, changes)
    local nodes = 0
    local maxDepth = 0
    walkPlan(optimized, function(node, depth)
        nodes += 1
        maxDepth = math.max(maxDepth, depth)
    end, 1)
    local estimatedRows, estimatedCost = estimate(optimized, catalog)
    local context = contextFor(index)
    local results = pack(pcall(execute, optimized, context))
    if not results[1] then
        emit("failed", names[index], results[2])
    else
        local output = results[2]
        local digest, balance = checksum(output)
        totals.digest = (totals.digest * 7 + digest) % 1000003
        totals.rows += #output
        totals.visits += context.visits
        totals.audit = (totals.audit + context.audit) % 1000003
        emit("plan", names[index], nodes, maxDepth, estimatedRows, estimatedCost, changes.merged)
        emit("result", #output, digest, balance, context.audit, context.cacheHits, context.cacheMisses)
        for effectIndex = 1, #context.effects do
            emit("effect", context.effects[effectIndex])
        end
        if output[1] then
            emit("first", output[1]:describe(), output[1].history)
        end
    end
end
local cost, depth = expressionCost(stage("project", scan("sales"), 1).expression)
emit("expression", cost, depth)
local function guardedProbe(kind, ...)
    local values = pack(...)
    local ok, result = pcall(function()
        if kind == "parameter" then
            return evaluate({ kind = "parameter", name = "missing" }, catalog.sales[1], {})
        elseif kind == "division" then
            return evaluate(binary("modulo", field("value"), literal(0)), catalog.sales[1], {})
        elseif kind == "table" then
            return execute(scan("missing"), contextFor(0))
        elseif kind == "seed" and seed < 0 then
            fail("NEGATIVE", seed)
        end
        return select(2, unpackAll(values))
    end)
    emit("probe", kind, ok, result)
end
guardedProbe("parameter", 1, nil, 3)
guardedProbe("division", 4, 5, 6)
guardedProbe("table", 7, 8, 9)
guardedProbe("seed", mode, seed + mode, nil)
emit("total", totals.digest, totals.rows, totals.visits, totals.audit)
for index = 1, #trace do
    print(trace[index])
end
`;

